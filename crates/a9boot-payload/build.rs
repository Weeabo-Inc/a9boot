//! Generates the payload's linker script from `a9boot-core`'s layout constants.
//!
//! This exists for one reason: the payload's link address and the host's
//! `abi::payload_exec_addr()` must be the same number, and a number written twice is a number
//! that will eventually disagree. The host computes where the payload will execute (the DFU
//! buffer's base plus the command header and the reply area); the linker script is built from
//! that same constant, so a change to either shows up as a link-time or plan-time failure
//! rather than as a payload that jumps into the wrong place.
//!
//! The `.bss`/stack layout is emitted here too, so the payload's footprint budget
//! (`layout::PAYLOAD_MAX_FOOTPRINT`) is a real number rather than an aspiration.

use std::io::Write;

fn main() {
    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR");
    let base = a9boot_core::abi::payload_exec_addr();
    let stack = a9boot_core::layout::PAYLOAD_STACK_SIZE;
    let budget = a9boot_core::layout::PAYLOAD_MAX_FOOTPRINT;

    let script = format!(
        "/* GENERATED by a9boot-payload/build.rs from a9boot-core::layout. Do not edit. */\n\
         ENTRY(_start)\n\
         SECTIONS\n\
         {{\n\
         \x20 . = {base:#x};\n\
         \x20 .text : ALIGN(4) {{\n\
         \x20   KEEP(*(.text._start))\n\
         \x20   *(.text .text.*)\n\
         \x20 }}\n\
         \x20 .rodata : ALIGN(8) {{ *(.rodata .rodata.*) }}\n\
         \x20 .data : ALIGN(8) {{ *(.data .data.*) *(.got .got.plt) }}\n\
         \x20 .bss (NOLOAD) : ALIGN(16) {{\n\
         \x20   __bss_start = .;\n\
         \x20   *(.bss .bss.*) *(COMMON)\n\
         \x20   __bss_end = .;\n\
         \x20 }}\n\
         \x20 . = ALIGN(16);\n\
         \x20 __image_end = .;\n\
         \x20 ASSERT(__image_end - {base:#x} <= {budget:#x} - {stack:#x},\n\
         \x20        \"a9boot payload image exceeds its footprint budget\")\n\
         \x20 . += {stack:#x};\n\
         \x20 __stack_top = .;\n\
         \x20 ASSERT(__stack_top - {base:#x} <= {budget:#x},\n\
         \x20        \"a9boot payload image plus stack exceeds PAYLOAD_MAX_FOOTPRINT\")\n\
         \x20 /DISCARD/ : {{ *(.comment) *(.eh_frame) *(.eh_frame_hdr) *(.ARM.exidx*) *(.note*) }}\n\
         }}\n"
    );

    let path = std::path::Path::new(&out_dir).join("a9boot-payload.ld");
    let mut f = std::fs::File::create(&path).expect("create linker script");
    f.write_all(script.as_bytes()).expect("write linker script");
    drop(f);

    println!("cargo:rustc-link-arg-bins=-T{}", path.display());
    println!("cargo:rustc-link-arg-bins=--gc-sections");
    // A map file, always. The payload's footprint is a first-class constraint (it has to fit the
    // transfer that delivers it), so the numbers are kept where they can be read rather than
    // being inferred from an assertion failure.
    let map = std::path::Path::new(&out_dir).join("a9boot-payload.map");
    println!("cargo:rustc-link-arg-bins=-Map={}", map.display());
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=../a9boot-core/src/layout.rs");
    println!("cargo:rerun-if-changed=../a9boot-core/src/abi.rs");
}
